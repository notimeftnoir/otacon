def is_sinkhole(result: DomainResult) -> bool:
    """Returns True if the domain resolves to known sinkhole or seizure indicators."""
    title = (result.page_title or "").lower()
    if any(sig in title for sig in _SINKHOLE_TITLES):
        return True

    for ns in result.ns_records:
        ns_lower = ns.lower()
        if any(sig in ns_lower for sig in _SINKHOLE_NAMESERVERS):
            return True

    return any(ip in _SINKHOLE_IPS for ip in result.ip_addresses)


def is_parked(result: DomainResult) -> bool:
    """Returns True if domain exhibits parking or domain-for-sale signals."""
    if result.is_sinkhole:
        return False

    title = (result.page_title or "").lower()
    server = (result.server_header or "").lower()
    if any(sig in title for sig in _PARKING_TITLES) or any(
        sig in server for sig in _PARKING_SERVERS
    ):
        return True

    for ns in result.ns_records:
        ns_lower = ns.lower()
        if any(sig in ns_lower for sig in _PARKING_NAMESERVERS):
            return True

    return any(any(ip.startswith(prefix) for prefix in _PARKING_IPS) for ip in result.ip_addresses)


def is_defensive(result: DomainResult, target: str) -> bool:
    """Returns True if variant redirects to target without an active MX record."""
    if not (result.redirects_to and target):
        return False
    if result.has_mx:
        return False
    parsed = parse_redirect(result.redirects_to)
    if parsed is None:
        return False
    host, _scheme = parsed
    canonical = target.lower().rstrip(".")
    return bool(host and (host == canonical or host.endswith("." + canonical)))


def _detect_sinkhole(result: DomainResult) -> None:
    if is_sinkhole(result):
        object.__setattr__(result, "is_sinkhole", True)


def _detect_parking(result: DomainResult) -> None:
    if is_parked(result):
        object.__setattr__(result, "is_parked", True)


def _detect_defensive(result: DomainResult, target: str) -> None:
    if is_defensive(result, target):
        object.__setattr__(result, "is_likely_defensive", True)


